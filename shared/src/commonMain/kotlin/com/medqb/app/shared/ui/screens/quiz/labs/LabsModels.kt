/**
 * The 4 official laboratory reference range categories:
 * Serum, Cerebrospinal, Blood, and Urine and BMI.
 */
enum class LabCategory(val displayName: String) {
    SERUM("Serum"),
    CEREBROSPINAL("Cerebrospinal"),
    BLOOD("Blood"),
    URINE_AND_BMI("Urine and BMI")
}
